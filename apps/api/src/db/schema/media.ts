import { index, integer, real, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';
import { tasks } from './tasks';

export const MEDIA_ROLES = ['video', 'question_image', 'upload'] as const;
/** What the media is for. Retention (FEAT-022) deletes only `video`; the rest is backed up. */
export type MediaRole = (typeof MEDIA_ROLES)[number];

export const MEDIA_KINDS = ['hls', 'mp4', 'image', 'audio'] as const;
export type MediaKind = (typeof MEDIA_KINDS)[number];

export const MEDIA_STATUSES = ['pending', 'uploading', 'ready', 'deleted'] as const;
/** `pending` → `uploading` (first chunk) → `ready` (verified); `deleted` once files are gone. */
export type MediaStatus = (typeof MEDIA_STATUSES)[number];

/**
 * A set of files on disk under `DATA_DIR/media/<dir>/` (an HLS ladder, an MP4, the pictures of a
 * lesson's questions, an admin upload). Served only through `GET /api/media/:id/*`.
 * The row stays after its files are deleted (`status = deleted`): transcripts and history refer
 * to it, so the task reference is `RESTRICT`.
 */
export const media = sqliteTable(
  'media',
  {
    id: integer().primaryKey({ autoIncrement: true }),
    taskId: integer().references(() => tasks.id, { onDelete: 'restrict' }),
    role: text().$type<MediaRole>().notNull(),
    kind: text().$type<MediaKind>().notNull(),
    /** Directory name under `DATA_DIR/media` (`[a-z0-9_-]`, generated by the server). */
    dir: text().notNull(),
    /** Total size of the files, known once the media is ready. */
    sizeBytes: integer(),
    /** Playback length of a video (seconds). */
    durationSec: real(),
    status: text().$type<MediaStatus>().notNull().default('pending'),
    /** Retention: the files may be deleted after this instant (epoch ms). */
    deleteAfter: integer(),
    /** Epoch milliseconds. */
    createdAt: integer().notNull(),
    readyAt: integer(),
    deletedAt: integer(),
  },
  (t) => [
    uniqueIndex('media_dir_uq').on(t.dir),
    index('media_task_idx').on(t.taskId),
    index('media_status_delete_after_idx').on(t.status, t.deleteAfter),
  ],
);

export type MediaRow = typeof media.$inferSelect;

/**
 * The files a media is made of, declared before the upload (path inside the media directory,
 * expected size and sha256). An upload accepts only declared files and `ready` requires all of
 * them to match.
 */
export const mediaFiles = sqliteTable(
  'media_files',
  {
    id: integer().primaryKey({ autoIncrement: true }),
    mediaId: integer()
      .notNull()
      .references(() => media.id, { onDelete: 'restrict' }),
    /** Relative path accepted by `safePath()` (e.g. `480p/seg_0001.ts`). */
    path: text().notNull(),
    sizeBytes: integer().notNull(),
    /** Lower-case hex. */
    sha256: text().notNull(),
  },
  (t) => [uniqueIndex('media_files_media_path_uq').on(t.mediaId, t.path)],
);

export type MediaFileRow = typeof mediaFiles.$inferSelect;
